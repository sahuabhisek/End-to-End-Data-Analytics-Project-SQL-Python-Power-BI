-- 	4. Data Analysis using SQL (Business Transactions)
-- We performed structured analysis in PostgreSQL to answer key business questions:
-- 1. Revenue by Gender – Compared total revenue generated by male vs. female 
-- customers.
SELECT gender,
SUM(Purchase_Amount) as total_revenue_gender
FROM  customer
GROUP BY gender;

-- Explanation:
-- - SUM() – Total revenue calculate karta hai.
-- - COUNT() – Total customer records count karta hai.
-- - GROUP BY – Gender-wise grouping karta hai.
-- - ORDER BY – Highest revenue pehle show karta hai.
-- Business Insight: Company ko pata chalega ki kis gender segment se zyada revenue 
generate ho raha hai.
-- Query 2. Discount & Spending Analysis
-- Interview Question: Un customers ko find karo jinhone discount use kiya aur 
-- jinka purchase amount overall average se equal ya greater hai.

SELECT
    Customer_ID,
    Gender,
    Item_Purchased,
    Purchase_Amount ,
    Discount_Applied
FROM customer
WHERE Discount_Applied = 'Yes'
AND Purchase_Amount  >= (
    SELECT AVG( Purchase_Amount)
    FROM  customer
)
ORDER BY Purchase_Amount  DESC;

--Query 3. Top 5 Products by Average Rating
SELECT
    Item_Purchased,
    ROUND(AVG(Review_Rating)::NUMERIC, 2)
        AS average_rating,
    COUNT(*) AS total_reviews
FROM customer
GROUP BY Item_Purchased
ORDER BY average_rating DESC
LIMIT 5;

--Query 4. Shipping Analysis
--Interview Question: Standard aur Express shipping mein average purchase amount compare karo.
SELECT
    Shipping_Type,
    COUNT(*) AS total_orders,
    ROUND(
        AVG(Purchase_Amount)::NUMERIC, 2
    ) AS average_purchase
FROM customer
WHERE Shipping_Type  IN ('Standard', 'Express')
GROUP BY Shipping_Type
ORDER BY average_purchase DESC;

-- Query 5. Subscription Analysis
-- Interview Question: Subscribers aur Non-subscribers ke customer count, 
-- average spending aur total revenue compare karo.
SELECT
    Subscription_Status,
    COUNT(DISTINCT Customer_ID) AS total_customers,
    ROUND(
        AVG(Purchase_Amount)::NUMERIC, 2
    ) AS average_spending,
    SUM(Purchase_Amount) AS total_revenue
FROM customer
GROUP BY Subscription_Status
ORDER BY total_revenue DESC;

-- Query 7. Customer Segmentation
-- Interview Question: Previous purchases ke basis par customers ko 
-- New, Returning aur Loyal categories mein divide karo
SELECT
    CASE
        WHEN Previous_Purchases <= 1
            THEN 'New Customer'
        WHEN Previous_Purchases BETWEEN 2 AND 5
            THEN 'Returning Customer'
        ELSE 'Loyal Customer'
    END AS customer_segment,

    COUNT(DISTINCT Customer_ID) AS total_customers,

    ROUND(
        AVG(Purchase_Amount)::NUMERIC, 2
    ) AS average_spending,

    SUM(Purchase_Amount) AS total_revenue

FROM customer
GROUP BY customer_segment
ORDER BY total_revenue DESC;

-- Query 8. Top 3 Most Purchased Products in Each Category
-- Interview Question: Har product category ke andar Top 3 most purchased products find karo.
WITH product_ranking AS
(
    SELECT
        Category,
        Item_Purchased,
        COUNT(*) AS total_purchases,

        DENSE_RANK() OVER (
            PARTITION BY Category
            ORDER BY COUNT(*) DESC
        ) AS product_rank

    FROM customer

    GROUP BY
        Category,
        Item_Purchased
)

SELECT
    Category,
    Item_Purchased,
    total_purchases,
    product_rank
FROM product_ranking
WHERE product_rank <= 3
ORDER BY Category, product_rank;

-- Query 9. Repeat Buyer & Subscription Analysis
-- Interview Question: Jinke previous purchases 5 se zyada hain, unmein subscribers aur non-subscribers kitne hain
SELECT
    Subscription_Status,
    COUNT(DISTINCT Customer_ID) AS total_customers,
    SUM(Purchase_Amount) AS total_revenue,

    ROUND(
        AVG(Purchase_Amount)::NUMERIC, 2
    ) AS average_purchase

FROM customer

WHERE Previous_Purchases > 5

GROUP BY Subscription_Status

ORDER BY total_customers DESC;

-- Query 10. Age Group Revenue Analysis
-- Interview Question: Different age groups ke according total revenue compare karo.
SELECT
    CASE
        WHEN Age BETWEEN 18 AND 25
            THEN '18-25'
        WHEN Age BETWEEN 26 AND 35
            THEN '26-35'
        WHEN Age BETWEEN 36 AND 50
            THEN '36-50'
        ELSE '50+'
    END AS age_group,

    COUNT(DISTINCT Customer_ID) AS total_customers,

    SUM(Purchase_Amount) AS total_revenue,

    ROUND(
        AVG(Purchase_Amount)::NUMERIC, 2
    ) AS average_purchase

FROM customer

GROUP BY age_group

ORDER BY total_revenue DESC;